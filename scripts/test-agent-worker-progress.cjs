async function snapshot(reviews, expandedIndex = -1, isRunning = true, workers = []) {
    const root = node('root');
    const app = renderer.createApp({ render: () => vue.h('div', { class: 'ambient-workers-list' }, [...workers.map(worker => vue.h(Component, { key: worker.id, worker, isRunning })), ...reviews.map(review => vue.h(Component, { key: review.id, review, isRunning }))]) });
    app.mount(root);
    if (expandedIndex >= 0) { toggle(all(root, el => el.type === 'article')[expandedIndex]).props.onClick(); await vue.nextTick(); }
    const escape = value => String(value).replace(/[&<>\"]/g, ch => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '\"': '&quot;' }[ch]));
    function serialize(el) {
        if (el.type === '#comment') return '';
        if (el.type === '#text') return escape(el.text);
        const attrs = Object.entries(el.props).filter(([key, value]) => !key.startsWith('on') && value != null).map(([key, value]) => ` ${key}="${escape(value)}"`).join('');
        return `<${el.type}${attrs}>${escape(el.text)}${el.children.map(serialize).join('')}</${el.type}>`;
    }
    const html = root.children.map(serialize).join('');
    app.unmount();
    return html;
}
